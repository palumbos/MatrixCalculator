package MatrixCalculator.analyzer;

/**
 * Enumeration of mathematical properties that a matrix can possess.
 */
public enum MatrixProperty {
    ZERO,
    IDENTITY,
    DIAGONAL,
    SCALAR,
    UPPER_TRIANGULAR,
    LOWER_TRIANGULAR,
    ROW,
    COLUMN,
    SQUARE,
    NON_SQUARE,
    SYMMETRIC,
    ANTISYMMETRIC
}
